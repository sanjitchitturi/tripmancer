export function getDestination(slug: string): Destination | undefined {
  return destinations.find((place) => place.slug === slug);
}

export function getOrigin(id: OriginId): Origin {
  return origins.find((origin) => origin.id === id) ?? origins[0];
}

export function typicalTripCost(place: Destination, originId: OriginId): number {
  const travelers = 2;
  const nights = 4;
  const days = 5;
  return (
    place.flights[originId] * travelers +
    place.stay.comfort * nights +
    place.foodPerDay * travelers * days +
    place.localPerDay * travelers * days
  );
}
